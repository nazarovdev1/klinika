const json = <T extends z.ZodType>(schema: T) => ({ content: { 'application/json': { schema } } });

/** Registers every endpoint that has no hand-written entry in openapi.ts. Money fields are strings. */
export function registerRemainingRoutes(
  registry: OpenAPIRegistry,
  security: Record<string, string[]>[],
): void {
  for (const op of OPS) {
    const params = [...op.path.matchAll(/\{(\w+)\}/g)].map((x) => x[1] ?? '');
    registry.registerPath({
      method: op.m,
      path: `/api/v1${op.path}`,
      tags: [op.tag],
      summary: op.summary,
      description: `Permission: ${op.perm}`,
      ...(op.noAuth ? {} : { security }),
      request: {
        ...(params.length
          ? {
              params: z.object(
                Object.fromEntries(params.map((p) => [p, p === 'id' ? id.shape.id : z.string()])),
              ),
            }
          : {}),
        ...(op.query ? { query: op.query } : {}),
        ...(op.body ? { body: json(op.body) } : {}),
        ...(op.idempotent
          ? { headers: z.object({ 'Idempotency-Key': z.string().min(8).max(100) }) }
          : {}),
      },
      responses: {
        [op.status ?? 200]: { description: 'Success' },
        ...(op.noAuth ? {} : { 401: { description: 'Unauthenticated', ...json(problemSchema) } }),
        403: { description: 'Forbidden', ...json(problemSchema) },
        422: { description: 'Validation error', ...json(problemSchema) },
      },
    });
  }
}

